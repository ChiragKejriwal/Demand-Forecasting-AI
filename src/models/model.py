def evaluate_forecast(
    y_true: np.ndarray,
    y_pred: np.ndarray,
) -> Dict[str, float]:
    """Calculate key forecast accuracy metrics (MAE, RMSE, WAPE, R2).

    Parameters
    ----------
    y_true : np.ndarray
        Ground-truth demand values.
    y_pred : np.ndarray
        Predicted demand values.

    Returns
    -------
    Dict[str, float]
        Dictionary containing calculated metrics.
    """
    y_true = np.asarray(y_true, dtype=float)
    y_pred = np.asarray(y_pred, dtype=float)

    mae = mean_absolute_error(y_true, y_pred)
    mse = mean_squared_error(y_true, y_pred)
    rmse = np.sqrt(mse)
    r2 = r2_score(y_true, y_pred)

    # Weighted Absolute Percentage Error (industry retail KPI)
    total_true = np.sum(y_true)
    wape = (np.sum(np.abs(y_true - y_pred)) / total_true) * 100.0 if total_true > 0 else 0.0

    # Mean Absolute Percentage Error (with epsilon for zero true demand)
    nonzero_mask = y_true > 0
    if np.any(nonzero_mask):
        mape = np.mean(np.abs((y_true[nonzero_mask] - y_pred[nonzero_mask]) / y_true[nonzero_mask])) * 100.0
    else:
        mape = 0.0

    metrics = {
        "mae": round(float(mae), 4),
        "rmse": round(float(rmse), 4),
        "wape_pct": round(float(wape), 2),
        "mape_pct": round(float(mape), 2),
        "r2_score": round(float(r2), 4),
    }

    logger.info(
        "Forecast Evaluation -> MAE: %.4f | RMSE: %.4f | WAPE: %.2f%% | R2: %.4f",
        metrics["mae"],
        metrics["rmse"],
        metrics["wape_pct"],
        metrics["r2_score"],
    )
    return metrics


def evaluate_temporal_test(
    model: DemandForecaster,
    test_df: pd.DataFrame,
    target_col: str = "units_sold",
) -> Tuple[Dict[str, float], pd.DataFrame]:
    """Evaluate a trained model on a temporal holdout test dataset.

    Parameters
    ----------
    model : DemandForecaster
        Fitted demand forecaster instance.
    test_df : pd.DataFrame
        Chronologically partitioned test DataFrame.
    target_col : str, optional
        Ground-truth column name, by default "units_sold".

    Returns
    -------
    Tuple[Dict[str, float], pd.DataFrame]
        Metrics dictionary and DataFrame with actual vs predicted values.
    """
    logger.info("Evaluating forecaster on temporal test set (%d samples)...", len(test_df))
    y_true = test_df[target_col].values
    y_pred = model.predict(test_df)

    metrics = evaluate_forecast(y_true, y_pred)

    results_df = test_df.copy()
    results_df["predicted_units_sold"] = np.round(y_pred, 2)
    results_df["absolute_error"] = np.round(np.abs(y_true - y_pred), 2)

    return metrics, results_df
